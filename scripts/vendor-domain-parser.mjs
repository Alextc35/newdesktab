import { build } from 'esbuild';
import { copyFile, mkdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const destination = new URL('src/shared/urls/vendor/', root);
const dependency = new URL('node_modules/tldts/', root);
const { version } = JSON.parse(await readFile(new URL('package.json', dependency), 'utf8'));
await mkdir(destination, { recursive: true });
await build({
  stdin: { contents: 'export { getDomain } from "tldts";', resolveDir: fileURLToPath(root), sourcefile: 'domain-parser-entry.js' },
  outfile: fileURLToPath(new URL('tldts.js', destination)),
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  legalComments: 'eof', banner: { js: `// Generated by scripts/vendor-domain-parser.mjs from tldts ${version}.` }
});
await copyFile(new URL('LICENSE', dependency), new URL('LICENSE.txt', destination));
console.log(`Vendored tldts ${version} for public-suffix domain boundaries.`);
