import { build } from 'esbuild';
import { copyFile, mkdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const destination = new URL('src/platform/backup/vendor/', root);
const dependency = new URL('node_modules/@zip.js/zip.js/', root);
const { version } = JSON.parse(await readFile(new URL('package.json', dependency), 'utf8'));
await mkdir(destination, { recursive: true });
await build({
  stdin: {
    contents: 'export { BlobReader, BlobWriter, ZipReader, ZipWriter } from "@zip.js/zip.js/lib/zip-core.js";',
    resolveDir: fileURLToPath(root),
    sourcefile: 'backup-zip-entry.js'
  },
  outfile: fileURLToPath(new URL('zip.js', destination)),
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  legalComments: 'eof',
  banner: { js: `// Generated by scripts/vendor-backup-zip.mjs from @zip.js/zip.js ${version}.` }
});
await copyFile(new URL('LICENSE', dependency), new URL('LICENSE.txt', destination));
console.log(`Vendored zip.js ${version} (core, local streams, no embedded worker or WASM).`);
